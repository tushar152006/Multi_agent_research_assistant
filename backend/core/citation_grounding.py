from __future__ import annotations

import hashlib
import re
from collections import Counter
from difflib import SequenceMatcher
from typing import Iterable

from pydantic import BaseModel, Field


class GroundedChunk(BaseModel):
    """A verified sentence or paragraph excerpt from a source paper."""

    chunk_id: str
    paper_title: str
    source: str
    section: str
    sentence_index: int
    text: str
    content_hash: str

    @classmethod
    def create(
        cls,
        paper_title: str,
        source: str,
        section: str,
        sentence_index: int,
        text: str,
    ) -> "GroundedChunk":
        normalized_text = text.strip()
        content_hash = hashlib.sha256(
            normalized_text.lower().encode("utf-8")
        ).hexdigest()[:12]
        chunk_id = f"{content_hash}_{sentence_index}"

        return cls(
            chunk_id=chunk_id,
            paper_title=paper_title,
            source=source,
            section=section,
            sentence_index=sentence_index,
            text=normalized_text,
            content_hash=content_hash,
        )


class CitationAnchor(BaseModel):
    """An exact verifiable citation attached to a synthesized insight or claim."""

    paper_title: str
    chunk_id: str
    exact_quote: str
    confidence_score: float = Field(ge=0.0, le=1.0)
    is_verified: bool = False


class GroundedClaim(BaseModel):
    """A synthesized claim or finding backed by one or more citation anchors."""

    claim_text: str
    category: str
    citations: list[CitationAnchor] = Field(default_factory=list)
    verification_status: str = "unverified"


class GroundingVerificationResult(BaseModel):
    """Report generated by the verification auditor."""

    total_claims: int
    verified_claims: int
    grounding_precision: float = Field(ge=0.0, le=1.0)
    claims: list[GroundedClaim]
    unsupported_claims: list[str] = Field(default_factory=list)


class CitationGroundingEngine:
    """Creates, anchors, and verifies citation-backed research claims."""

    _TOKEN_PATTERN = re.compile(r"[a-z0-9]+(?:'[a-z0-9]+)?", re.IGNORECASE)
    _SENTENCE_PATTERN = re.compile(r"(?<=[.!?])\s+|\n{2,}")

    def segment_into_chunks(
        self,
        paper_title: str,
        source: str,
        text: str,
        section: str = "abstract",
    ) -> list[GroundedChunk]:
        chunks: list[GroundedChunk] = []

        for sentence_index, sentence in enumerate(
            self._SENTENCE_PATTERN.split(text.strip())
        ):
            cleaned = re.sub(r"\s+", " ", sentence).strip()
            if len(cleaned) <= 25:
                continue

            chunks.append(
                GroundedChunk.create(
                    paper_title=paper_title,
                    source=source,
                    section=section,
                    sentence_index=sentence_index,
                    text=cleaned,
                )
            )

        return chunks

    def build_chunk_index(
        self,
        chunks: list[GroundedChunk],
    ) -> dict[str, GroundedChunk]:
        index: dict[str, GroundedChunk] = {}

        for chunk in chunks:
            index[chunk.chunk_id] = chunk

            for token in self._tokens(chunk.text):
                index.setdefault(token, chunk)

        return index

    def anchor_claim(
        self,
        claim: str,
        category: str,
        candidate_chunks: list[GroundedChunk],
        threshold: float = 0.6,
    ) -> GroundedClaim:
        claim_tokens = set(self._tokens(claim))
        ranked: list[tuple[float, GroundedChunk]] = []

        for chunk in candidate_chunks:
            chunk_tokens = set(self._tokens(chunk.text))
            if not claim_tokens or not chunk_tokens:
                continue

            overlap = len(claim_tokens & chunk_tokens) / len(claim_tokens)
            similarity = SequenceMatcher(
                None,
                self._normalize(claim),
                self._normalize(chunk.text),
            ).ratio()

            score = max(overlap, similarity)
            if score >= threshold:
                ranked.append((score, chunk))

        ranked.sort(key=lambda item: item[0], reverse=True)

        citations = [
            CitationAnchor(
                paper_title=chunk.paper_title,
                chunk_id=chunk.chunk_id,
                exact_quote=chunk.text,
                confidence_score=round(score, 4),
            )
            for score, chunk in ranked[:3]
        ]

        return GroundedClaim(
            claim_text=claim,
            category=category,
            citations=citations,
            verification_status="unverified",
        )

    def verify_synthesis(
        self,
        claims: list[GroundedClaim],
        source_chunks: list[GroundedChunk],
    ) -> GroundingVerificationResult:
        chunks_by_id = {chunk.chunk_id: chunk for chunk in source_chunks}
        verified_claims = 0
        unsupported_claims: list[str] = []
        audited_claims: list[GroundedClaim] = []

        for claim in claims:
            verified_anchors: list[CitationAnchor] = []

            for anchor in claim.citations:
                source_chunk = chunks_by_id.get(anchor.chunk_id)
                is_verified = False

                if source_chunk is not None:
                    quote = self._normalize(anchor.exact_quote)
                    source_text = self._normalize(source_chunk.text)

                    is_verified = (
                        bool(quote)
                        and (
                            quote in source_text
                            or SequenceMatcher(
                                None,
                                quote,
                                source_text,
                            ).ratio()
                            >= 0.85
                        )
                    )

                verified_anchors.append(
                    anchor.model_copy(update={"is_verified": is_verified})
                )

            if not verified_anchors:
                status = "unverified"
            elif all(anchor.is_verified for anchor in verified_anchors):
                status = "verified"
            elif any(anchor.is_verified for anchor in verified_anchors):
                status = "partially_verified"
            else:
                status = "unverified"

            audited_claim = claim.model_copy(
                update={
                    "citations": verified_anchors,
                    "verification_status": status,
                }
            )
            audited_claims.append(audited_claim)

            if status == "verified":
                verified_claims += 1
            else:
                unsupported_claims.append(claim.claim_text)

        total_claims = len(audited_claims)
        precision = verified_claims / total_claims if total_claims else 0.0

        return GroundingVerificationResult(
            total_claims=total_claims,
            verified_claims=verified_claims,
            grounding_precision=round(precision, 4),
            claims=audited_claims,
            unsupported_claims=unsupported_claims,
        )

    def _tokens(self, text: str) -> list[str]:
        return self._TOKEN_PATTERN.findall(text.lower())

    def _normalize(self, text: str) -> str:
        return " ".join(self._tokens(text))


def extract_grounded_chunks(value: object) -> list[GroundedChunk]:
    """Extract GroundedChunk instances from nested reader-agent output values."""

    if isinstance(value, GroundedChunk):
        return [value]

    if isinstance(value, dict):
        chunks: list[GroundedChunk] = []

        if "grounded_chunks" in value:
            chunks.extend(extract_grounded_chunks(value["grounded_chunks"]))

        for nested_value in value.values():
            chunks.extend(extract_grounded_chunks(nested_value))

        return chunks

    if isinstance(value, Iterable) and not isinstance(value, (str, bytes)):
        chunks = []
        for item in value:
            chunks.extend(extract_grounded_chunks(item))
        return chunks

    grounded_chunks = getattr(value, "grounded_chunks", None)
    if grounded_chunks is not None:
        return extract_grounded_chunks(grounded_chunks)

    return []
