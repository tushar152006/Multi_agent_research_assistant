from __future__ import annotations

import re
from datetime import datetime, timezone
from typing import Sequence

from backend.models.schemas import ResearchResponse


class AcademicExporterService:
    """Service for generating standard academic publication artifacts (BibTeX and Systematic Review Markdown)."""

    def generate_bibtex(self, report: ResearchResponse) -> str:
        """Generate valid BibTeX entries for all cited papers."""
        entries: list[str] = []

        papers = report.papers
        if not papers and report.reader_outputs:
            # Fallback to reader outputs if raw papers are empty (e.g. document upload)
            for idx, ro in enumerate(report.reader_outputs, start=1):
                key = f"paper_{idx}"
                entries.append(
                    f"@article{{{key},\n"
                    f"  title = {{{ro.title}}},\n"
                    f"  author = {{Unknown}},\n"
                    f"  journal = {{Ingested Literature}},\n"
                    f"  year = {{{datetime.now(timezone.utc).year}}}\n"
                    f"}}"
                )
            return "\n\n".join(entries)

        for paper in papers:
            # Generate clean BibTeX cite key: e.g. "smith2024multiagent"
            first_author = "anon"
            if paper.authors:
                cleaned = re.sub(r"[^a-zA-Z]", "", paper.authors[0].split()[-1]).lower()
                if cleaned:
                    first_author = cleaned

            # Extract year from 4-digit pattern or arXiv YYMM format
            arxiv_match = re.search(r"arxiv:(\d{2})(\d{2})", paper.external_id or "", re.IGNORECASE)
            year_match = re.search(r"\b(20\d\d|19\d\d)\b", f"{paper.title} {paper.abstract}")

            if year_match:
                year = year_match.group(1)
            elif arxiv_match:
                year = f"20{arxiv_match.group(1)}"
            else:
                year = str(datetime.now(timezone.utc).year)

            first_title_word = re.sub(r"[^a-zA-Z]", "", paper.title.split()[0]).lower() if paper.title else "paper"
            cite_key = f"{first_author}{year}{first_title_word}"

            author_str = " and ".join(paper.authors) if paper.authors else "Unknown Authors"

            entry = (
                f"@article{{{cite_key},\n"
                f"  title = {{{paper.title}}},\n"
                f"  author = {{{author_str}}},\n"
                f"  journal = {{{paper.source}}},\n"
                f"  year = {{{year}}},\n"
                f"  note = {{Identifier: {paper.external_id}}}\n"
                f"}}"
            )
            entries.append(entry)

        return "\n\n".join(entries)

    def generate_markdown_report(self, report: ResearchResponse) -> str:
        """Generate a complete, publication-ready academic systematic review report."""
        lines: list[str] = []
        gen_date = report.generated_at.strftime("%B %d, %Y")

        lines.append(f"# Systematic Literature Review: {report.query.title()}")
        lines.append(f"*Generated by Multi-Agent Research Assistant on {gen_date}*")
        lines.append(f"**Session ID:** `{report.session_id}` | **Query Type:** `{report.query_type}`")
        lines.append("\n---\n")

        # 1. Executive Summary
        lines.append("## 1. Executive Summary")
        lines.append(report.summary)
        lines.append("\n")

        # 2. PRISMA 2020 Systematic Review Flow
        if report.prisma_flow:
            pf = report.prisma_flow
            lines.append("## 2. PRISMA 2020 Systematic Review Protocol")
            lines.append(
                f"- **Records Identified:** {pf.get('total_identified', 0)}\n"
                f"- **Duplicates Removed:** {pf.get('duplicates_removed', 0)}\n"
                f"- **Records Screened:** {pf.get('records_screened', 0)}\n"
                f"- **Records Excluded:** {pf.get('records_excluded', 0)}\n"
                f"- **Studies Included in Meta-Analysis:** {pf.get('studies_included', 0)}\n"
            )
            flowchart = pf.get("mermaid_flowchart", "")
            if flowchart:
                lines.append("### PRISMA Flow Diagram")
                lines.append("```mermaid")
                lines.append(flowchart)
                lines.append("```\n")

            audit = pf.get("audit_trail", [])
            if audit:
                lines.append("### Screening & Eligibility Audit Trail")
                lines.append("| Paper Title | Source | Stage | Status | Relevance | Justification |")
                lines.append("| :--- | :--- | :--- | :--- | :--- | :--- |")
                for item in audit:
                    lines.append(
                        f"| {item.get('paper_title')} | {item.get('source')} | "
                        f"{item.get('stage')} | **{item.get('status').upper()}** | "
                        f"{item.get('relevance_score')}% | {item.get('reason')} |"
                    )
                lines.append("\n")

        # 3. Cross-Paper Contradiction Matrix
        if report.contradiction_matrix:
            cm = report.contradiction_matrix
            lines.append("## 3. Cross-Paper Contradiction Matrix & Tension Analysis")
            tensions = cm.get("tensions", [])
            lines.append(
                f"- **Pairs Evaluated:** {cm.get('total_pairs_checked', 0)}\n"
                f"- **Tensions Detected:** {len(tensions)}\n"
                f"- **Matrix Tension Density:** {round(cm.get('matrix_density', 0) * 100, 1)}%\n"
                f"- **Highest Tension Paper:** {cm.get('most_controversial_paper', 'None')}\n"
            )

            debates = cm.get("key_open_debates", [])
            if debates:
                lines.append("### Key Open Scientific Debates")
                for d in debates:
                    lines.append(f"- **{d}**")
                lines.append("\n")

            if tensions:
                lines.append("### Pairwise Empirical Discrepancies")
                for t in tensions:
                    lines.append(f"#### [{t.get('severity', '').replace('_', ' ').upper()}] {t.get('topic')}")
                    lines.append(f"- **Paper A ({t.get('paper_a')}):** {t.get('claim_a')}")
                    lines.append(f"- **Paper B ({t.get('paper_b')}):** {t.get('claim_b')}")
                    lines.append(f"- **Root Cause:** {t.get('root_cause')}")
                    lines.append(f"- **Resolution Hypothesis:** *{t.get('resolution_hypothesis')}* (Confidence: {int(t.get('confidence', 0) * 100)}%)\n")

        # 4. Multi-Paper Evidence & Concept Graph
        if report.evidence_graph:
            eg = report.evidence_graph
            lines.append("## 4. Multi-Paper Evidence & Knowledge Graph")
            concepts = eg.get("central_concepts", [])
            if concepts:
                lines.append(f"**Dominant Cross-Paper Concepts:** {', '.join(concepts)}\n")

            diag = eg.get("mermaid_diagram", "")
            if diag:
                lines.append("```mermaid")
                lines.append(diag)
                lines.append("```\n")

        # 5. Synthesis, Innovations & Gaps
        if report.analysis:
            lines.append("## 5. Thematic Synthesis & Innovations")
            lines.append("### Key Themes")
            for th in report.analysis.themes:
                lines.append(f"- {th}")
            lines.append("\n### Innovations")
            for inn in report.analysis.innovations:
                lines.append(f"- **{inn.paper_title}:** {inn.innovation} *(Impact: {inn.impact})*")
            lines.append("\n### Identified Gaps")
            for gap in report.analysis.gaps:
                lines.append(f"- {gap}")
            lines.append("\n")

        # 6. Actionable Implementation Plan
        if report.implementation_plan:
            plan = report.implementation_plan
            lines.append("## 6. Implementation Roadmap")
            lines.append(f"**Project Concept:** {plan.project_idea}\n")
            lines.append(f"**Value Proposition:** {plan.value_proposition}\n")

            lines.append("### Roadmap Milestones")
            for phase in plan.mvp_roadmap:
                lines.append(f"#### Phase: {phase.name} ({phase.duration})")
                for g in phase.goals:
                    lines.append(f"- [ ] {g}")
            lines.append("\n")

        # 7. BibTeX Bibliography
        lines.append("## 7. BibTeX References")
        lines.append("```bibtex")
        lines.append(self.generate_bibtex(report))
        lines.append("```\n")

        return "\n".join(lines)
